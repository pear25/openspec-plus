#!/usr/bin/env node
// Build the user-level `spec-driven` schema override from the installed
// package schema plus this repo's overlay/. Upstream text is kept as is;
// overlay text is appended, so package improvements still arrive on upgrade.
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SCHEMA = "spec-driven";
const overlayDir = join(dirname(fileURLToPath(import.meta.url)), "..", "overlay");
const dataHome = process.env.XDG_DATA_HOME || join(homedir(), ".local/share");
const outDir = join(dataHome, "openspec/schemas", SCHEMA);

// Resolve the package that the `openspec` on PATH runs, and reuse its yaml lib.
const bin = execFileSync("realpath", [execFileSync("which", ["openspec"]).toString().trim()]).toString().trim();
const pkgDir = dirname(dirname(bin));
const require = createRequire(join(pkgDir, "package.json"));
const YAML = require("yaml");
const srcDir = join(pkgDir, "schemas", SCHEMA);

const schema = YAML.parse(readFileSync(join(srcDir, "schema.yaml"), "utf8"));
const overlay = YAML.parse(readFileSync(join(overlayDir, "overlay.yaml"), "utf8")) ?? {};

for (const [id, add] of Object.entries(overlay.artifacts ?? {})) {
  const artifact = schema.artifacts.find((a) => a.id === id);
  if (!artifact) throw new Error(`overlay targets unknown artifact "${id}" (upstream schema changed?)`);
  artifact.instruction = `${artifact.instruction.trimEnd()}\n\n${add.append.trimEnd()}\n`;
}
if (overlay.apply?.append) {
  schema.apply.instruction = `${schema.apply.instruction.trimEnd()}\n\n${overlay.apply.append.trimEnd()}\n`;
}
schema.description = `${schema.description} (+ local overlay)`;

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
cpSync(join(srcDir, "templates"), join(outDir, "templates"), { recursive: true });

const tplOverlay = join(overlayDir, "templates");
if (existsSync(tplOverlay)) {
  for (const name of readdirSync(tplOverlay)) {
    const target = join(outDir, "templates", name);
    if (!existsSync(target)) throw new Error(`overlay template "${name}" has no upstream counterpart`);
    const base = readFileSync(target, "utf8").trimEnd();
    writeFileSync(target, `${base}\n${readFileSync(join(tplOverlay, name), "utf8")}`);
  }
}

writeFileSync(
  join(outDir, "schema.yaml"),
  `# GENERATED by openspec-plus (scripts/build-schema.mjs) - edit the overlay, not this file.\n${YAML.stringify(schema, { lineWidth: 0 })}`,
);
execFileSync("openspec", ["schema", "validate", SCHEMA], { stdio: "inherit" });
console.log(`Built ${outDir} from ${srcDir} + overlay`);
